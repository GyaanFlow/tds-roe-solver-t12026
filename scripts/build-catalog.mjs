const endAt = page.indexOf(END);
if (startAt < 0 || endAt < startAt) throw new Error('index.html is missing the CATALOG:START / CATALOG:END markers.');
let nextPage = page.slice(0, startAt) + renderHtml(terms) + page.slice(endAt + END.length);
const seoStart = nextPage.indexOf('<!-- SEO:START');
const seoEnd = nextPage.indexOf('<!-- SEO:END -->');
if (seoStart < 0 || seoEnd < seoStart) throw new Error('index.html is missing the SEO:START / SEO:END markers.');
nextPage = nextPage.slice(0, seoStart) + renderSeoHead(terms) + nextPage.slice(seoEnd + '<!-- SEO:END -->'.length);
// Intro description, derived from tds-config.json so new terms / GAs / projects appear without edits.
// It deliberately avoids the words "answer" and "solution" (IITM academic-integrity rules).
function joinList(items) {
  return items.length <= 1 ? items.join('') : `${items.slice(0, -1).join(', ')} and ${items[items.length - 1]}`;
}
function describePortal(config) {
  const entries = Object.entries(config.terms).filter(([, term]) => term.active !== false);
  const examIds = new Set(entries.flatMap(([, term]) => term.exams));
  const numbers = (prefix) => [...examIds].map((id) => id.match(new RegExp(`^${prefix}(\\d+)$`))?.[1]).filter(Boolean).map(Number).sort((a, b) => a - b);
  const gas = numbers('ga');
  const projects = numbers('p');
  const parts = [];
  if (gas.length) parts.push(gas.length === 1 ? `GA${gas[0]}` : `GA${gas[0]}–GA${gas[gas.length - 1]}`);
  if (examIds.has('roe')) parts.push('ROE');
  if (projects.length) parts.push(`Project ${projects.join(' & ')}`);
  if (examIds.has('endterm')) parts.push('end-term practice');
  const byYear = new Map();
  for (const [id] of entries) {
    const match = id.match(/^T(\d+)(\d{4})$/);
    if (!match) continue;
    byYear.set(match[2], [...(byYear.get(match[2]) ?? []), `T${match[1]}`]);
  }
  const span = joinList([...byYear].map(([year, labels]) => `${joinList(labels.sort())} ${year}`));
  return `Tools in Data Science (TDS) solver for IIT Madras TDS community: step-by-step guides for ${joinList(parts)} across ${span}.`;
}
const FORBIDDEN_WORDS = /\b(answers?|solutions?)\b/i;
const portalConfig = JSON.parse(fs.readFileSync(path.join(root, 'tds-config.json'), 'utf8'));
const description = describePortal(portalConfig);
if (FORBIDDEN_WORDS.test(description)) throw new Error(`Generated description contains a forbidden word: ${description}`);
const escAttr = (value) => esc(value);
nextPage = nextPage
  .replace(/(<p id="welcomeDescription"[^>]*>)[^<]*(<\/p>)/, (_, open, close) => `${open}${esc(description)}${close}`)
  .replace(/(<meta name="description" content=")[^"]*(")/, (_, open, close) => `${open}${escAttr(description)}${close}`)
  .replace(/(<meta property="og:description" content=")[^"]*(")/, (_, open, close) => `${open}${escAttr(description)}${close}`)
  .replace(/(<meta name="twitter:description" content=")[^"]*(")/, (_, open, close) => `${open}${escAttr(description)}${close}`);
const configText = fs.readFileSync(path.join(root, 'tds-config.json'), 'utf8');
const nextConfigText = configText.replace(/("termDescription":\s*)"[^"]*"/, (_, key) => `${key}${JSON.stringify(description)}`);
const extraFiles = { 'robots.txt': renderRobots(), 'sitemap.xml': renderSitemap(), 'tds-config.json': nextConfigText };
const nextJson = renderJson(terms);

if (process.argv.includes('--check')) {
  // Git on Windows may check files out with CRLF; compare content, not line endings.
  const lf = (text) => text.split(String.fromCharCode(13, 10)).join(String.fromCharCode(10));
  const stale = [];
  if (lf(nextPage) !== lf(page)) stale.push('index.html');
  if (!fs.existsSync(jsonPath) || lf(fs.readFileSync(jsonPath, 'utf8')) !== lf(nextJson)) stale.push('catalog.json');
  for (const [name, body] of Object.entries(extraFiles)) {
    const file = path.join(root, name);
    if (!fs.existsSync(file) || lf(fs.readFileSync(file, 'utf8')) !== lf(body)) stale.push(name);
  }
  if (stale.length) {
    console.error(`Out of date: ${stale.join(', ')}. Run: node scripts/build-catalog.mjs`);
    process.exit(1);
  }
  console.log('Solver catalog is up to date.');
} else {
  fs.writeFileSync(htmlPath, nextPage);
  fs.writeFileSync(jsonPath, nextJson);
  for (const [name, body] of Object.entries(extraFiles)) fs.writeFileSync(path.join(root, name), body);
  console.log(`Catalog written: ${terms.length} terms, ${terms.reduce((s, t) => s + t.exams.length, 0)} exams.`);
}
