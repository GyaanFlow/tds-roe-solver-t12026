function registerQ4Interactive() {
  if (typeof window === 'undefined' || window._p1q4Registered) return;
  window._p1q4Registered = true;

  window._p1q4Generate = async function () {
    const bucketName = document.getElementById('p1q4BucketName')?.value || '';
    const location = document.getElementById('p1q4Location')?.value || 'asia-south1';
    const aipipeToken = document.getElementById('p1q4Token')?.value || '';
    const fileInput = document.getElementById('p1q4File');
    const statusEl = document.getElementById('p1q4GenStatus');

    const errors = validateNotebookInputs({ bucketName, location, aipipeToken });
    if (errors.length > 0) {
      if (statusEl) {
        statusEl.style.color = '#dc3545';
        statusEl.textContent = errors.join(' ');
      }
      return;
    }

    let fileB64 = null;
    let fileName = null;
    const file = fileInput?.files?.[0];
    if (file) {
      try {
        fileB64 = await readFileAsBase64(file);
        fileName = file.name;
      } catch (err) {
        if (statusEl) {
          statusEl.style.color = '#dc3545';
          statusEl.textContent = `Could not read the selected file: ${err.message}`;
        }
        return;
      }
    }

    const cells = buildQ4NotebookCells({ bucketName, location, aipipeToken, fileB64, fileName });
    downloadIpynb('q4_gcp_dataset_upload.ipynb', cells);

    if (statusEl) {
      statusEl.style.color = '#198754';
      statusEl.textContent = file
        ? 'Downloaded q4_gcp_dataset_upload.ipynb with your eval.jsonl already embedded — upload it at colab.research.google.com and run cells top to bottom.'
        : 'Downloaded q4_gcp_dataset_upload.ipynb — Cell 3 will ask you to pick eval.jsonl when you run it. Upload at colab.research.google.com and run cells top to bottom.';
    }
  };
}

