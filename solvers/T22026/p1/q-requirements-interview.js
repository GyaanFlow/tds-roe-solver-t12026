import { normalizeEmail } from './utils.js';

export const id = 'q-interview-requirements-audio';
export const title = 'Q1: AI Problem Discovery — Requirements Interview';

export async function solve(email) {
  const norm = normalizeEmail(email);

  const summary = [
    `Record a 60–120s audio of discovery questions for a bank VP, share a Google Drive folder`,
    `(recording.mp3 + questions.md only) with se2002@ds.study.iitm.ac.in, and submit the folder link.`,
    `This cannot be auto-generated for you — it's graded on how specific and diagnostic YOUR`,
    `questions are, and identical AI-written submissions all score low. Follow the guide below.`
  ].join(' ');

  const guide = [
    `## Q1 — Requirements Interview: step-by-step (for ${norm})`,
    ``,
    `### The scenario`,
    `You're an AI consultant. A bank VP of Risk & Credit says: **"We want to use AI to help us`,
    `make better lending decisions."** That's all you get. "Better" could mean faster, more`,
    `accurate, more approvals, more consistent, fairer, or more compliant — each points to a`,
    `completely different AI solution. Your job in the first 10 minutes is to find out which one`,
    `is real, before anyone builds anything.`,
    ``,
    `### What you must produce`,
    `1. **A 60–120 second audio recording** of yourself speaking the exact questions you'd ask`,
    `   this VP, naturally, as if you're in the room — not a robotic read-through of a checklist.`,
    `2. **A Google Drive folder** containing exactly two files, no more, no subfolders:`,
    `   - \`recording.mp3\` — the audio above`,
    `   - \`questions.md\` — your written questions plus your conditional follow-ups`,
    `3. Share that folder with **se2002@ds.study.iitm.ac.in** (Editor or Viewer — either works).`,
    `4. Submit the **folder** link (not a file link):`,
    `   \`https://drive.google.com/drive/folders/FOLDER_ID\``,
    ``,
    `### How to actually write good questions (the part that's graded)`,
    `Weak questions assume a solution already exists: *"What AI model are you thinking of?"*,`,
    `*"What's your budget?"* — these skip the one question that matters: **is there a real,`,
    `measurable problem at all?**`,
    ``,
    `Strong questions are diagnostic — they force the VP to get specific and reveal what "better"`,
    `actually means:`,
    `- "Walk me through how a lending decision is made today — what data does your team look at,`,
    `  and how long does it take end to end?"`,
    `- "When you say 'better decisions', what does that mean specifically — fewer defaults,`,
    `  faster approvals, more approvals, or something else?"`,
    `- "In the last quarter, can you point to a specific loan that went wrong — someone who`,
    `  defaulted, or a good customer you rejected?"`,
    `- "What's your current default rate, and what would be acceptable with AI?"`,
    `- "If the AI approves a loan and the borrower defaults, who's accountable?"`,
    ``,
    `Write **at least 5 questions**, each ending with \`?\`.`,
    ``,
    `### Conditional follow-ups (this is the part most people skip)`,
    `A conditional follow-up is a question you plan *in advance*, based on what the VP might say —`,
    `it proves you've thought through multiple realities before walking in. Write each one in`,
    `three parts: **trigger → question → why**.`,
    ``,
    `Example:`,
    `- **Trigger:** If they say "better" means fewer defaults →`,
    `- **Question:** "What's your current default rate, and what reduction would matter? Is the`,
    `  target 10% fewer defaults, or 50%?"`,
    `- **Why:** This tells me whether we're solving a small calibration problem (feature`,
    `  engineering) or a fundamental model failure (a complete rebuild).`,
    ``,
    `You need **at least 2 conditionals**, each with a real trigger, a real follow-up question,`,
    `and a reason explaining what you'd learn and why it matters. A conditional with no reasoning`,
    `line gets zero marks for that item.`,
    ``,
    `### Recording it`,
    `- Any phone voice recorder, or a free tool like [Vocaroo](https://vocaroo.com), works fine —`,
    `  export/download as \`.mp3\`.`,
    `- Read your \`questions.md\` out loud naturally, in the order you'd actually ask them,`,
    `  60–120 seconds total. Under 60s reads as shallow; over 120s means you haven't prioritized.`,
    `- The questions in the audio should match what's written in \`questions.md\`.`,
    ``,
    `### Setting up the Drive folder correctly`,
    `1. Go to [drive.google.com](https://drive.google.com), click **New → Folder**, name it`,
    `   anything (e.g. \`tds-p1-q1\`).`,
    `2. Drag in your two files, named **exactly** \`recording.mp3\` and \`questions.md\` — no`,
    `   extra files, no subfolders.`,
    `3. Right-click the folder → **Share** → add \`se2002@ds.study.iitm.ac.in\` → set to`,
    `   Viewer or Editor → **Send**.`,
    `4. Open the folder and copy the URL from your browser's address bar — it should look like`,
    `   \`https://drive.google.com/drive/folders/1aBcDeFgHiJkLmNoPqRsTuVwXyZ\`. That's your answer.`,
    ``,
    `### Grading rubric (10 marks, graded offline by LLMs)`,
    `| Criterion | Marks | What it checks |`,
    `|---|---|---|`,
    `| Question quality | 4 | Diagnostic, specific to lending — not generic tooling/budget questions |`,
    `| Conditional follow-ups | 3 | ≥2 conditionals, each with trigger + question + reasoning |`,
    `| Audio delivery | 2 | 60–120s, audible, sounds like a real conversation, matches the written version |`,
    `| Problem-discovery focus | 1 | Oriented at finding a real problem, not proposing/evaluating AI tools |`,
    ``,
    `**Grading is relative** — a generic ChatGPT-written script scores the same (low) as every`,
    `other generic script everyone else submits. Think about what YOU, specifically, would need`,
    `to know before recommending anything to this VP.`,
    ``,
    `### Common mistakes that cost marks`,
    `- Submitting a **file** link instead of a **folder** link`,
    `- Forgetting to share with \`se2002@ds.study.iitm.ac.in\``,
    `- Wrong filenames (must be exactly \`recording.mp3\` and \`questions.md\`)`,
    `- Extra files or subfolders in the shared folder`,
    `- Fewer than 5 questions, or conditionals with no reasoning`,
    `- Folder access revoked or folder deleted before grading — **you must keep it accessible`,
    `  after the deadline**, or you get zero marks`,
    ``,
    `Once you have your folder link, paste it into the exam's answer box for this question`,
    `(a URL input starting with \`https://drive.google.com\`).`
  ].join('\n');

  return {
    type: 'guide',
    answer: summary,
    variant: `Requirements interview checklist for ${norm}`,
    answerDisplay: [
      `### Q1: AI Problem Discovery — Requirements Interview`,
      ``,
      `This question can't be auto-solved — it's graded on the specificity of the questions`,
      `YOU personally would ask, plus a real 60–120s audio recording of you asking them.`,
      ``,
      summary,
      ``,
      `See the full step-by-step guide below (recording tips, example questions, Drive setup,`,
      `full rubric, and common mistakes to avoid).`
    ].join('\n'),
    guide
  };
}
